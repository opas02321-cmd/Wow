local function cleanText(s)
    s = tostring(s or ""):gsub("<[^>]->", "")
    s = s:gsub("&amp;", "&"):gsub("&lt;", "<"):gsub("&gt;", ">")
    s = s:gsub("&quot;", '"'):gsub("&apos;", "'"):gsub(" ", " ")
    return trim(s:gsub("%s+", " "))
end
local function normalized(s)

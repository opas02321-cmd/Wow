                and not has(t,"풀이 중엔 채팅") and not has(t,"모두 제출했어요")
                and not has(t,"다음 라운드") and not has(t,"정답 첫 자음") then
                local score=math.min(length,250)
                if has(t,"?") then score=score+80 end
                local name=object.Name:lower()
                if name:find("question",1,true) or name:find("quiz",1,true) then score=score+100 end
                if has(t,"코인") or has(t,"로벅스") or has(t,"구매") then score=score-180 end
                if score>bestScore then bestText,bestObject,bestScore=t,object,score end
            end
        end
    end
    questionObject=bestObject
    return bestText
end
local function commonAncestorDepth(a,b)
    if not a or not b then return 0 end
    local ancestors={}
    local current=a
    while current and current~=PG do ancestors[current]=true;current=current.Parent end
    current=b
    while current and current~=PG do
        if ancestors[current] then
            local depth=0
            while current and current~=PG do depth=depth+1;current=current.Parent end
            return depth
        end
        current=current.Parent
    end
    return 0
end
local function getAnswerBox()
    local best,bestScore=nil,-math.huge
    for box in pairs(boxes) do
        if effectivelyVisible(box) and box.AbsoluteSize.X>100 and box.TextEditable then
            local placeholder=cleanText(box.PlaceholderText)
            local name=box.Name:lower()
            local score=commonAncestorDepth(questionObject,box)*30
            if has(placeholder,"정답") then score=score+160 end
            if has(placeholder,"입력") or has(placeholder,"쓰세요") then score=score+50 end
            if name:find("answer",1,true) then score=score+100 end
            if has(placeholder,"검색") or name:find("search",1,true) then score=score-250 end
            if score>bestScore then best,bestScore=box,score end
        end
    end
    return best
end
local function humanType(text,box)
    if typingBusy or not box then return end
    cancelTyping()
    local generation=typingGeneration
    typingBusy=true
    local expectedQuestion=lastQuestionText
    local boundaries={}
    for byteIndex in utf8.codes(text) do table.insert(boundaries,byteIndex) end
    table.insert(boundaries,#text+1)
    local ok=pcall(function() box.Text="" end)
    if not ok then typingBusy=false;return end
    task.spawn(function()
        for i=1,#boundaries-1 do
            if generation~=typingGeneration or not autoFill or expectedQuestion~=lastQuestionText then break end
            if not box.Parent or not effectivelyVisible(box) then
                if generation==typingGeneration then lastTypedQuestion="" end
                break
            end
            local wrote=pcall(function() box.Text=text:sub(1,boundaries[i+1]-1) end)
            if not wrote then
                if generation==typingGeneration then lastTypedQuestion="" end
                break
            end
            task.wait(math.random(40,90)/1000)
        end
        if generation==typingGeneration then typingBusy=false end
    end)
end


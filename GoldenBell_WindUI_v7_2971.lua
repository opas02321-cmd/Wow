local function wordByte(b)
    return b and ((b>=48 and b<=57) or (b>=65 and b<=90) or (b>=97 and b<=122) or b>=128)
end
local function asciiWordByte(b)
    return b and ((b>=48 and b<=57) or (b>=65 and b<=90) or (b>=97 and b<=122))
end
local function safeFind(text, key)
    if key == "" then return false end
    local count, start = charCount(key), 1
    while true do
        local s,e = text:find(key,start,true)
        if not s then return false end
        if count > 2 then return true end
        local before, after = wordByte(text:byte(s-1)), wordByte(text:byte(e+1))
        if not before and (count > 1 or not after) then return true end
        start = e+1
    end
end
local function findEnglishWord(text, word)
    local start = 1
    while true do
        local s,e = text:find(word,start,true)
        if not s then return false end
        if not asciiWordByte(text:byte(s-1)) and not asciiWordByte(text:byte(e+1)) then return true end
        start = e+1
    end
end
local function findKoreanTerm(text, term)
    local start = 1
    while true do
        local s,e = text:find(term,start,true)
        if not s then return false end
        -- 앞말의 일부인 '쥐'가 '다람쥐'보다 먼저 선택되는 것을 막음.
        if not wordByte(text:byte(s-1)) then
            if not wordByte(text:byte(e+1)) then return true end
            local rest=text:sub(e+1)
            for _,particle in ipairs({"를","을","은","는","이","가","의","에","와","과","도"}) do
                if rest:sub(1,#particle)==particle and not wordByte(rest:byte(#particle+1)) then return true end
            end
        end
        start = e+1
    end
end

-- 3. 동적 수학 계산. UTF-8 연산자를 바이트 문자 집합에 넣지 않음.
local function formatNumber(n)
    if n ~= n or n == math.huge or n == -math.huge then return nil end
    if math.abs(n) < 1e-10 then n=0 end
    if math.abs(n - math.floor(n+0.5)) < 1e-9 then return string.format("%.0f", n) end
    return (string.format("%.8f",n):gsub("0+$",""):gsub("%.$",""))
end
local function has(s, token) return s:find(token,1,true) ~= nil end
local function solveMath(question)
    local q = cleanText(question):lower()
    q = q:gsub("×","*"):gsub("÷","/"):gsub("−","-"):gsub("–","-")
    q = q:gsub("㎝","cm"):gsub("센티미터","cm"):gsub("㎟","mm2"):gsub("㎠","cm2")
    local compact = q:gsub("%s+","")
    local function positiveNumbers(s)
        local values = {}
        for number in s:gmatch("%d+%.?%d*") do table.insert(values,tonumber(number)) end
        return values
    end
    -- 도형 문제에서는 단위에 붙은 제곱 숫자를 길이로 해석하지 않음.
    local shapeq = compact:gsub("cm2", "cm"):gsub("m2", "m"):gsub("제%d+문제", "")
    local nums = positiveNumbers(shapeq)
    local area, perimeter = has(compact,"넓이"), has(compact,"둘레")
    local lengthUnit
    local mixedUnit = false
    for u in shapeq:gmatch("%d+%.?%d*([a-z]+)") do
        if u=="mm" or u=="cm" or u=="m" or u=="km" then
            if lengthUnit and lengthUnit ~= u then mixedUnit=true end
            lengthUnit=u
        end
    end
    if (area or perimeter) and not mixedUnit then
        if has(compact,"정사각형") and nums[1] and nums[1] > 0 then
            return formatNumber(area and nums[1]^2 or nums[1]*4)
        elseif has(compact,"직사각형") and nums[1] and nums[2] and nums[1]>0 and nums[2]>0 then
            return formatNumber(area and nums[1]*nums[2] or (nums[1]+nums[2])*2)
        elseif has(compact,"삼각형") and area and nums[1] and nums[2] and has(compact,"밑변") and has(compact,"높이") then
            return formatNumber(nums[1]*nums[2]/2)
        elseif (has(compact,"원의") or has(compact,"원둘레") or has(compact,"원넓이")) and nums[1] then
            local diameter = has(compact,"지름") and not has(compact,"반지름")
            local radius = has(compact,"반지름")
            if diameter or radius then
                local r=diameter and nums[1]/2 or nums[1]
                local pi=3.14
                local customPi=compact:match("원주율[%=:은을]*([%d%.]+)")
                if customPi then pi=tonumber(customPi) or pi end
                return formatNumber(area and r*r*pi or 2*r*pi)
            end
        end
    end
    local arithmetic = has(q,"계산") or has(q,"얼마") or has(q,"값") or has(q,"=") or has(q,"답")
    local exprq = compact:gsub("[xX]","*")
    -- 괄호 없는 하나의 이항식만 계산. 연쇄식을 앞부분만 계산하지 않음.
    local a,op,b = exprq:match("([%-]?%d+%.?%d*)([%+%-%*/])([%-]?%d+%.?%d*)")
    if a and (arithmetic or exprq:match("^[%-]?%d+%.?%d*[%+%-%*/][%-]?%d+%.?%d*%??$")) then
        local expression = a..op..b
        local rest = exprq:gsub(expression:gsub("(%W)","%%%1"),"",1)
        if not rest:find("[%+%*/]") and not rest:find("%-%d") and not has(q,"(") and not has(q,")") then
            a,b=tonumber(a),tonumber(b)
            if op=="+" then return formatNumber(a+b) end
            if op=="-" then return formatNumber(a-b) end
            if op=="*" then return formatNumber(a*b) end
            if op=="/" and b~=0 then return formatNumber(a/b) end
        end
    end
    local a2,b2=q:match("(%d+%.?%d*)에서%s*(%d+%.?%d*)[을를]+%s*빼")
    if a2 then return formatNumber(tonumber(a2)-tonumber(b2)) end
    return nil
end

local function lookup(question)
    local q = cleanText(question)
    local lower, norm = q:lower(), normalized(q)
    local direct = quizDB[q]
    if direct then return direct, q, categories[q] or "사용자 추가" end
    -- 영어 단어가 직접 나온 한국어 뜻 문제를 먼저 처리.
    if has(q,"뜻") or has(q,"우리말") or has(q,"한국어") or has(q,"의미") or has(q,"한글로") then
        for _,row in ipairs(reverseWords) do
            if findEnglishWord(lower,row.word) then return row.answer,row.key,row.category end
        end
    end
    if has(q,"영어") or has(q,"영문") or has(q,"영단어") then
        for _,row in ipairs(forwardWords) do
            if findKoreanTerm(q,row.term) then return row.answer,row.key,row.category end
        end
    end
    local mathAnswer=solveMath(q)
    if mathAnswer then return mathAnswer,"수학 계산","수학" end
    -- 긴 설명 우선. 공백/따옴표/문장부호 차이는 항목 추가 없이 처리.
    for _,row in ipairs(index) do
        local isForward = row.term ~= nil
        local isReverse = row.word ~= nil
        if not isForward and not isReverse then
            if safeFind(q,row.key) or (row.length>=4 and has(norm,row.norm)) then
                return row.answer,row.key,row.category
            end
        end
    end
    return nil
end

